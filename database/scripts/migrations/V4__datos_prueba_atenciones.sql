DECLARE @Pacientes TABLE
(
    Documento NVARCHAR(20),
    IdPaciente INT
);

INSERT INTO @Pacientes (Documento, IdPaciente)
SELECT Documento, IdPaciente
FROM dbo.Paciente
WHERE Documento IN
(
    '12345678',
    '23456789',
    '34567890',
    '45678901',
    '56789012',
    '67890123',
    '78901234',
    '89012345'
);
GO


-- ATENCIONES
INSERT INTO dbo.Atencion
(
    IdPaciente,
    FechaAtencion,
    Facturado,
    Valor
)
SELECT 
    P.IdPaciente,
    A.FechaAtencion,
    A.Facturado,
    A.Valor
FROM
(
    VALUES
        ('12345678', '2024-01-15 08:30:00', 1, 150000),
        ('12345678', '2024-01-20 10:00:00', 0, 250000),
        ('12345678', '2024-02-10 14:30:00', 0, 180000),
        ('23456789', '2024-01-18 09:00:00', 0, 320000),
        ('23456789', '2024-02-05 11:30:00', 0, 275000),
        ('34567890', '2024-01-22 08:00:00', 0, 450000),
        ('45678901', '2024-01-25 15:00:00', 0, 190000),
        ('45678901', '2024-02-15 09:30:00', 1, 220000),
        ('45678901', '2024-02-20 16:00:00', 0, 310000),
        ('56789012', '2024-02-01 10:30:00', 0, 180000),
        ('67890123', '2024-02-08 08:00:00', 0, 420000),
        ('67890123', '2024-02-18 13:00:00', 0, 350000),
        ('78901234', '2024-01-30 09:00:00', 0, 280000),
        ('78901234', '2024-02-12 11:00:00', 1, 195000),
        ('78901234', '2024-02-25 15:30:00', 0, 340000),
        ('89012345', '2024-02-20 10:00:00', 0, 500000)
) AS A
(
    Documento,
    FechaAtencion,
    Facturado,
    Valor
)
INNER JOIN dbo.Paciente P
    ON P.Documento = A.Documento;
